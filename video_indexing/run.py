def save_video_records(video_id, records, parquet_name, row_index):

    video_folder = PER_VIDEO_DIR / parquet_name
    video_folder.mkdir(parents=True, exist_ok=True)

    final_path = video_folder / f"{row_index:06d}.jsonl"
    temp_path = video_folder / f"{row_index:06d}.tmp"

    with open(temp_path, "w", encoding="utf-8") as f:

        for record in records:

            f.write(
                json.dumps(record, ensure_ascii=False) + "\n"
            )

        f.flush()
        os.fsync(f.fileno())

    os.replace(temp_path, final_path)

    return final_path


