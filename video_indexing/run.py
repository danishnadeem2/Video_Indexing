def get_video_rotation(video_bytes, stream):

    rotation = 0

    try:
        result = subprocess.run(
            [
                "ffprobe",
                "-v", "error",
                "-select_streams", "v:0",
                "-show_entries",
                "stream_tags=rotate:stream_side_data=rotation",
                "-of", "json",
                "-i", "pipe:0"
            ],
            input=video_bytes,
            capture_output=True,
            timeout=60
        )

        if result.returncode == 0:

            info = json.loads(result.stdout)
            streams = info.get("streams", [])

            if streams:
                stream_info = streams[0]

                side_data = stream_info.get(
                    "side_data_list", []
                )

                for item in side_data:
                    if "rotation" in item:
                        rotation = -float(item["rotation"])
                        return int(round(rotation / 90) * 90) % 360

                tags = stream_info.get("tags", {})

                if "rotate" in tags:
                    rotation = float(tags["rotate"])
                    return int(round(rotation / 90) * 90) % 360

    except Exception:
        pass

    # Fallback to PyAV metadata
    try:
        rotation = float(stream.metadata.get("rotate", 0))
    except Exception:
        rotation = 0

    return int(round(rotation / 90) * 90) % 360


def apply_rotation(frame, clockwise_rotation):

    rotation = int(clockwise_rotation) % 360

    if rotation not in (0, 90, 180, 270):
        raise ValueError(f"Invalid rotation: {rotation}")

    if rotation == 90:
        return np.rot90(frame, k=3).copy()

    elif rotation == 180:
        return np.rot90(frame, k=2).copy()

    elif rotation == 270:
        return np.rot90(frame, k=1).copy()

    return frame

# People-count median helper
def calculate_people_median(histogram):

    total_frames = sum(histogram.values())

    if total_frames == 0:
        return 0

    positions = [
        (total_frames - 1) // 2,
        total_frames // 2
    ]

    values = []
    cumulative = 0

    for count in sorted(histogram):

        cumulative += histogram[count]

        while positions and cumulative > positions[0]:
            values.append(count)
            positions.pop(0)

        if not positions:
            break

    if len(values) == 1:
        return values[0]

    return (values[0] + values[1]) // 2

# Per-video processing function
def process_video(video_bytes, video_id):

    stats = defaultdict(lambda: {
        "frames": 0,
        "objects": Counter(),
        "people_hist": Counter()
    })

    frame_buffer = []
    timestamp_buffer = []

    frame_index = 0
    first_timestamp = None
    last_second = None

    processing_error = None
    normal_eof = False
    container = None

    def infer_buffer():

        nonlocal last_second

        if not frame_buffer:
            return

        results = model.predict(
            source=frame_buffer,
            imgsz=IMG_SIZE,
            conf=CONFIDENCE,
            iou=IOU_THRESHOLD,
            classes=TARGET_CLASSES,
            device=DEVICE,
            half=HALF_PRECISION,
            verbose=False
        )

        if len(results) != len(frame_buffer):
            raise RuntimeError(
                "Inference result count does not match frame count."
            )

        for result, second in zip(results, timestamp_buffer):

            classes = []

            if result.boxes is not None and result.boxes.cls is not None:
                classes = (
                    result.boxes.cls.detach()
                    .cpu()
                    .numpy()
                    .astype(int)
                    .tolist()
                )

            counts = Counter(classes)
            people_count = counts.get(0, 0)

            stats[second]["frames"] += 1
            stats[second]["people_hist"][people_count] += 1

            for class_id in set(classes):
                if class_id in CLASS_NAMES:
                    stats[second]["objects"][class_id] += 1

            if last_second is None or second > last_second:
                last_second = second

        frame_buffer.clear()
        timestamp_buffer.clear()

    try:

        container = av.open(io.BytesIO(video_bytes))

        if not container.streams.video:
            raise ValueError("No video stream found.")

        stream = container.streams.video[0]

        fps = (
            float(stream.average_rate)
            if stream.average_rate
            else 0.0
        )

        rotation = get_video_rotation(video_bytes, stream)

        for frame in container.decode(video=0):

            timestamp = frame.time

            if timestamp is None:

                if frame.pts is not None and frame.time_base is not None:
                    timestamp = float(frame.pts * frame.time_base)

                elif fps > 0:
                    timestamp = frame_index / fps

                else:
                    raise ValueError(
                        "Frame timestamp unavailable and FPS unknown."
                    )

            timestamp = float(timestamp)

            if not math.isfinite(timestamp):
                raise ValueError("Invalid frame timestamp.")

            if first_timestamp is None:
                first_timestamp = timestamp

            relative_time = max(
                0.0,
                timestamp - first_timestamp
            )

            second = int(math.floor(relative_time))

            image = frame.to_ndarray(format="bgr24")
            image = apply_rotation(image, rotation)

            frame_buffer.append(image)
            timestamp_buffer.append(second)

            frame_index += 1

            if len(frame_buffer) >= INFERENCE_BATCH_SIZE:
                infer_buffer()

        normal_eof = True
        infer_buffer()

        if frame_index == 0:
            raise ValueError("No frames decoded.")

    except Exception as exc:

        processing_error = (
            f"{type(exc).__name__}: {str(exc)}"
        )

        try:
            infer_buffer()
        except Exception as batch_exc:
            processing_error += (
                f" | Pending batch failed: {batch_exc}"
            )

    finally:

        if container is not None:
            container.close()

    # Generate per-second records
    records = []

    if last_second is not None:

        final_second = (
            last_second if normal_eof
            else last_second - 1
        )

        for second in range(final_second + 1):

            data = stats.get(second)

            if data is None or data["frames"] == 0:

                records.append({
                    "video": video_id,
                    "second": second,
                    "objects": [],
                    "people": 0
                })

                continue

            frame_count = data["frames"]
            detected_objects = []

            for class_id, object_name in CLASS_NAMES.items():

                present_count = data["objects"].get(
                    class_id, 0
                )

                if present_count * 2 >= frame_count:
                    detected_objects.append(object_name)

            records.append({
                "video": video_id,
                "second": second,
                "objects": sorted(detected_objects),
                "people": calculate_people_median(
                    data["people_hist"]
                )
            })

    if processing_error:

        records.append({
            "video": video_id,
            "error": processing_error
        })

    return records, frame_index

